import { chromium } from '@playwright/test';
const base = process.env.BASE_URL || 'http://127.0.0.1:3000';
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(String(e)));
await page.goto(base, { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.getByRole('heading', { name: '一念起，万物生。' }).waitFor({ timeout: 60000 });
await page.getByRole('button', { name: '众生图鉴' }).first().click();
await page.getByLabel('搜索人物').fill('陆青崖');
await page.getByRole('button', { name: /陆青崖/ }).first().click();
await page.getByRole('dialog', { name: '陆青崖的生平' }).waitFor();
await page.getByRole('dialog', { name: '陆青崖的生平' }).getByRole('button', { name: /储物袋/ }).click();
await page.getByRole('dialog', { name: '陆青崖的生平' }).getByRole('button', { name: '功法', exact: true }).click();
await page.getByRole('button', { name: '关闭人物详情' }).click();
await page.getByRole('button', { name: '因果事件' }).first().click();
await page.getByRole('button', { name: '推进一日' }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: '/tmp/living-dashboard.png', fullPage: false });
console.log('Dashboard smoke passed; page errors:', errors.length);
const game = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const gameErrors = [];
game.on('pageerror', e => gameErrors.push(String(e)));
await game.goto(base + '/game/index.html?auto=new', { waitUntil: 'domcontentloaded', timeout: 60000 });
await game.waitForFunction(() => window.__game?.npcs?.living?.people?.length > 900, null, { timeout: 90000 });
const count = await game.evaluate(() => window.__game.npcs.living.people.length);
await game.waitForTimeout(1500);
await game.screenshot({ path: '/tmp/living-game.png' });
console.log('Original game smoke passed; living NPCs:', count, 'page errors:', gameErrors.length);
if (errors.length) console.log(errors.slice(0, 5));
if (gameErrors.length) console.log(gameErrors.slice(0, 5));
await browser.close();
if (errors.length || gameErrors.length) process.exitCode = 1;
